/*
 * oled.c — SSD1306 72x40 over I2C (legacy driver). Text only.
 * If the image is horizontally shifted, adjust OLED_COL_OFFSET.
 * If it's mirrored/upside-down, flip the segremap (0xA1/0xA0) and COM scan
 * (0xC8/0xC0) bytes in the init sequence.
 */
